/**
 * Writes thin pointer files for AI tools that don't read AGENTS.md directly, so every tool
 * follows the same rules. Run after editing AGENTS.md (npm run ai does it).
 */
import { mkdirSync, writeFileSync } from 'node:fs';

const note = 'Generated by scripts/agent-pointers.mjs. Edit AGENTS.md instead.';
const body =
  'Follow the rules in AGENTS.md at the repository root: build UI from @ds/react components, ' +
  'use only documented props (ai/components/{id}.json), use tokens instead of raw values, keep ' +
  'everything accessible, and run `npx ds-validate` before finishing.';

mkdirSync('.cursor/rules', { recursive: true });
writeFileSync(
  '.cursor/rules/design-system.mdc',
  `---\ndescription: Design-system rules for all UI code\nalwaysApply: true\n---\n\n<!-- ${note} -->\n\n${body}\n`,
);
mkdirSync('.github', { recursive: true });
writeFileSync('.github/copilot-instructions.md', `<!-- ${note} -->\n\n${body}\n`);
