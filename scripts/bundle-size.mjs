/**
 * Bundle-size report for @ds/react (run after build-lib). For each component: the minified,
 * gzipped JS and CSS an app pays for when it imports only that component. React, Radix,
 * lucide-react and downshift are external (shared across components); tokens.css is
 * reported once. Writes docs/bundle-size.md.
 */
import { build } from 'esbuild';
import { build as viteBuild } from 'vite';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { readFileSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';

const dist = 'packages/react/dist';
const components = [
  ...readFileSync('packages/react/src/components/index.ts', 'utf8').matchAll(/from '\.\.\/(\w+)'/g),
].map((m) => m[1]);
const external = [
  'react',
  'react-dom',
  'react/jsx-runtime',
  '@radix-ui/*',
  'lucide-react',
  'downshift',
  '@ds/tokens',
];
const kb = (bytes) => (bytes / 1024).toFixed(1);

// Measured the way apps build: Vite (Rolldown) tree-shakes unused components and their CSS.
const measure = async (code) => {
  const dir = mkdtempSync(join(tmpdir(), 'ds-size-'));
  const entry = join(dir, 'entry.js');
  writeFileSync(entry, code);
  const out = await viteBuild({
    configFile: false,
    logLevel: 'silent',
    build: {
      write: false,
      minify: true,
      lib: { entry, formats: ['es'], fileName: 'x' },
      rollupOptions: {
        external: (id) =>
          external.some((e) => (e.endsWith('*') ? id.startsWith(e.slice(0, -1)) : id === e)),
      },
    },
  });
  const files = (Array.isArray(out) ? out : [out]).flatMap((o) => o.output);
  const size = (ext) =>
    files
      .filter((f) => f.fileName.endsWith(ext))
      .reduce((n, f) => n + gzipSync(f.type === 'chunk' ? f.code : f.source).length, 0);
  return { js: size('.js'), css: size('.css') };
};
const libIndex = resolve(dist, 'index.js');

const rows = [];
for (const name of [...new Set(components)]) {
  const exportName =
    readFileSync(`packages/react/src/${name}/index.ts`, 'utf8').match(/export \{\s*(\w+)/)?.[1] ??
    name;
  const { js, css } = await measure(`export { ${exportName} } from '${libIndex}';`);
  rows.push({ name, js, css });
}
rows.sort((a, b) => b.js + b.css - (a.js + a.css));

const tokens = await build({
  entryPoints: ['packages/tokens/dist/tokens.css'],
  bundle: true,
  minify: true,
  write: false,
  outdir: 'out',
  logLevel: 'silent',
  external: ['*.woff2', '*.woff', '*.png', '@fontsource/*'],
});
const tokensGz = gzipSync(tokens.outputFiles[0].contents).length;
const whole = await measure(`export * from '${libIndex}';`);
const allGz = whole.js + whole.css;

const md = [
  '# Bundle size',
  '',
  'Generated by `node scripts/bundle-size.mjs` after `node scripts/build-lib.mjs`. Minified and gzipped;',
  'React, Radix, lucide-react and downshift are shared dependencies and not counted.',
  '',
  `- **Tokens** (\`@ds/tokens/tokens.css\`, every theme): ${kb(tokensGz)} kB, loaded once.`,
  `- **Whole library** (every component, JS + CSS): ${kb(allGz)} kB.`,
  '- **One component**: an app that imports only that component pays roughly this (tree-shaking):',
  '',
  '| Component | JS (kB) | CSS (kB) |',
  '|---|---:|---:|',
  ...rows.map((r) => `| ${r.name} | ${kb(r.js)} | ${kb(r.css)} |`),
  '',
];
writeFileSync('docs/bundle-size.md', md.join('\n'));
console.log(
  `Tokens ${kb(tokensGz)} kB · library ${kb(allGz)} kB · largest: ${rows
    .slice(0, 3)
    .map((r) => `${r.name} ${kb(r.js + r.css)} kB`)
    .join(', ')}`,
);
